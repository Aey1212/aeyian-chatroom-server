"""Build the display-name fonts in packages/fonts/name-fonts/.

Every font comes from google/fonts at one pinned commit and is checked against the sha256 recorded
in name-fonts.lock.json. Fonts whose licence declares a Reserved Font Name are only converted to
WOFF2; OFL clause 3 would otherwise require renaming them. The others are pinned to one weight when
they are variable, and CJK/Hangul faces are split into unicode-range chunks so a name only fetches
the glyphs it uses.
"""

