ID_PATTERN = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")


def css_family(font: NameFont) -> str:
    return f"NameFont-{font.id}"


def ofl_body() -> str:
    text = OFL_BODY_SOURCE.read_text()
    start = text.index("-----------------------------------------------------------\nSIL OPEN FONT LICENSE")
    return text[start:]


def license_header(text: str) -> str:
    return text.split("PREAMBLE", 1)[0]


def reserved_font_name(text: str) -> str | None:
    header = " ".join(license_header(text).split())
    match = re.search(r"Reserved Font Names?\s+(.+?)(?:\.\s|$|This Font Software)", header)
    return match.group(1).strip().rstrip(".") if match else None


def fetch(cache: Path, rel: str, allow_missing: bool = False) -> bytes | None:
    dest = cache / SOURCE_COMMIT / rel
    if dest.is_file():
        return dest.read_bytes()
    try:
        blob = _http_get(f"{RAW_BASE}/{rel}")
    except Exception as error:  # noqa: BLE001 - reported with the path
        if allow_missing and "404" in str(error):
            return None
        raise SystemExit(f"download failed for {rel}: {error}") from error
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(blob)
    return blob


def license_text(cache: Path, font: NameFont, sfnt: bytes) -> tuple[str, str | None]:
    rel = f"{font.directory}/OFL.txt"
    blob = fetch(cache, rel, allow_missing=True)
    if blob is not None:
        return blob.decode("utf-8-sig").replace("\r\n", "\n"), rel
    # A few families ship without OFL.txt; the font's own name table states the licence.
    parsed = TTFont(io.BytesIO(sfnt), lazy=True)
    names = parsed["name"]
    description = names.getDebugName(13) or ""
    if "Open Font License, Version 1.1" not in description:
        raise SystemExit(f"{font.id}: no OFL.txt and the name table does not state OFL 1.1")
    copyright_line = names.getDebugName(0) or ""
    text = (
        f"{copyright_line}\n\n"
        "This Font Software is licensed under the SIL Open Font License, Version 1.1.\n"
        "This license is copied below, and is also available with a FAQ at:\n"
        "https://openfontlicense.org\n\n\n"
        f"{ofl_body()}"
    )
    return text, None


# Japanese fonts often draw Cyrillic and Greek full-width; those letters do not read as names.
WIDTH_SAMPLES = {
    "latin": "abcdefghijklmnopqrstuvwxyz",
    "cyrillic": "абвгдежзийклмнопрстуфхцчшщъыьэюя",
    "greek": "αβγδεζηθικλμνξοπρστυφχψω",
}
MAX_WIDTH_VS_LATIN = 1.4


def median_width(font: TTFont, text: str) -> float | None:
    cmap = font.getBestCmap()
    widths = sorted(font["hmtx"][cmap[ord(c)]][0] for c in text if ord(c) in cmap)
    return widths[len(widths) // 2] if widths else None


def coverage(font: TTFont) -> list[str]:
    cmap = set(font.getBestCmap())
    scripts = [script for script, test in SCRIPT_TESTS.items() if test(cmap)]
    latin = median_width(font, WIDTH_SAMPLES["latin"])
    for script in ("cyrillic", "greek"):
        width = median_width(font, WIDTH_SAMPLES[script])
        if script in scripts and latin and width and width > latin * MAX_WIDTH_VS_LATIN:
            scripts.remove(script)
    return scripts


def woff2_unchanged(sfnt: bytes) -> bytes:
    source = io.BytesIO(sfnt)
    out = io.BytesIO()
    woff2.compress(source, out)
    return out.getvalue()


def instance_at_pinned_weight(sfnt: bytes) -> tuple[bytes, str]:
    font = TTFont(io.BytesIO(sfnt), recalcTimestamp=False)
    limits = {}
    for axis in font["fvar"].axes:
        if axis.axisTag == "wght":
            limits["wght"] = min(max(PINNED_WEIGHT, axis.minValue), axis.maxValue)
        else:
            limits[axis.axisTag] = axis.defaultValue
    static = instantiateVariableFont(font, limits, updateFontNames=False)
    static["OS/2"].usWeightClass = int(limits["wght"])
    buffer = io.BytesIO()
    static.save(buffer)
    pins = ", ".join(f"{tag}={value:g}" for tag, value in sorted(limits.items()))
    return buffer.getvalue(), pins


def to_woff2(sfnt: bytes) -> bytes:
    font = TTFont(io.BytesIO(sfnt), lazy=True, recalcTimestamp=False, recalcBBoxes=False)
    font.flavor = "woff2"
    buffer = io.BytesIO()
    font.save(buffer)
    return buffer.getvalue()


def _chunk_job(job: tuple[str, tuple[int, ...]]) -> bytes:
    path, codepoints = job
    return subset_face(Path(path).read_bytes(), codepoints)


def cmap_of(blob: bytes) -> set[int]:
    return set(TTFont(io.BytesIO(blob), lazy=True).getBestCmap())


@dataclass
class Built:
    font: NameFont
    upstream: str
    upstream_sha256: str
    license_upstream: str | None
    license_text: str
    reserved_name: str | None
    scripts: list[str]
    weight: str
    treatment: str
    files: list[tuple[str, bytes, list[int]]]  # (path under files/, woff2, codepoints)


def build_font(font: NameFont, cache: Path, stage: Path, pool: ProcessPoolExecutor | None, lock: dict) -> Built:
    rel = f"{font.directory}/{font.file}"
    sfnt = fetch(cache, rel)
    digest = sha256_bytes(sfnt)
    locked = lock.get("fonts", {}).get(font.id, {})
    if locked.get("upstream") == rel and locked.get("upstreamSha256") not in (None, digest):
        raise SystemExit(f"{font.id}: {rel} does not match the sha256 in {LOCK_PATH.name}")
    text, license_rel = license_text(cache, font, sfnt)
    reserved = reserved_font_name(text)
    source = TTFont(io.BytesIO(sfnt), lazy=True)
    cmap = set(source.getBestCmap())
    scripts = coverage(source)
    variable = "fvar" in source
    base = f"{font.id}/{font.id}"

    if reserved:
        # OFL clause 3: a Modified Version may not use the reserved name, so this file is only
        # repackaged. Variable fonts keep their axis and declare its weight range.
        blob = woff2_unchanged(sfnt)
        if cmap_of(blob) != cmap:
            raise SystemExit(f"{font.id}: WOFF2 conversion changed the character map")
        if variable:
            axis = next(a for a in source["fvar"].axes if a.axisTag == "wght")
            weight = f"{axis.minValue:g} {axis.maxValue:g}"
        else:
            weight = "100 900"
        return Built(font, rel, digest, license_rel, text, reserved, scripts, weight,
                     "WOFF2 conversion only (reserved font name)", [(f"{base}.woff2", blob, sorted(cmap))])

    steps = []
    if variable:
        sfnt, pins = instance_at_pinned_weight(sfnt)
        steps.append(f"instanced at {pins}")
        if set(TTFont(io.BytesIO(sfnt), lazy=True).getBestCmap()) != cmap:
            raise SystemExit(f"{font.id}: instancing changed the character map")

    if not CHUNKED_SCRIPTS & set(scripts):
        steps.append("WOFF2")
        return Built(font, rel, digest, license_rel, text, None, scripts, "100 900",
                     ", ".join(steps), [(f"{base}.woff2", to_woff2(sfnt), sorted(cmap))])

    static_path = stage / f"{font.id}.ttf"
    static_path.write_bytes(sfnt)
    ordered = sorted(cmap)
    per_chunk, _ = calibrate_chunk_size(sfnt, ordered, CHUNK_TARGET_BYTES)
    plan = plan_chunks(cmap, per_chunk)
    jobs = [(str(static_path), chunk) for chunk in plan]
    blobs = list(pool.map(_chunk_job, jobs)) if pool else [_chunk_job(job) for job in jobs]
    files = []
    covered: set[int] = set()
    for index, (chunk, blob) in enumerate(zip(plan, blobs)):
        chunk_cmap = cmap_of(blob)
        if chunk_cmap != set(chunk):
            raise SystemExit(f"{font.id}: chunk {index} character map drifted from the plan")
        covered |= chunk_cmap
        files.append((f"{base}.{index:03d}.woff2", blob, sorted(chunk_cmap)))
    if covered != cmap:
        raise SystemExit(f"{font.id}: chunks do not cover the whole character map")
    steps.append(f"split into {len(files)} unicode-range chunks, WOFF2")
    return Built(font, rel, digest, license_rel, text, None, scripts, "100 900", ", ".join(steps), files)


def render_stylesheet(built: list[Built]) -> str:
    rules = [SPDX_CSS_HEADER, f"/* {GENERATED_HEADER} */", ""]
    for item in built:
        for path, _, codepoints in item.files:
            rules.append(
                "@font-face {\n"
                f"\tfont-family: '{css_family(item.font)}';\n"
                f"\tsrc: url('./files/{path}') format('woff2');\n"
                f"\tfont-weight: {item.weight};\n"
                "\tfont-style: normal;\n"
                "\tfont-display: swap;\n"
                f"\tunicode-range: {format_unicode_range(codepoints)};\n"
                "}"
            )
    return "\n".join(rules) + "\n"


def render_manifest(built: list[Built]) -> str:
    return json.dumps(
        {
            "_comment": f"{GENERATED_HEADER} Paths are relative to packages/fonts/name-fonts/.",
            "fonts": [
                {
                    "id": item.font.id,
                    "label": item.font.label,
                    "category": item.font.category,
                    "family": css_family(item.font),
                    "scripts": item.scripts,
                    "license": f"licenses/{item.font.id}.txt",
                }
                for item in built
            ],
        },
        ensure_ascii=False,
        indent="\t",
    ) + "\n"


def render_notice(built: list[Built]) -> str:
    lines = [
        "# Display-name font licences",
        "",
        f"<!-- {GENERATED_HEADER} -->",
        "",
        "Every font in `files/` is licensed under the SIL Open Font License, Version 1.1. Each",
        "font's copyright notice and licence text are in `licenses/<id>.txt` and accompany it.",
        "",
        f"Source: https://github.com/{SOURCE_REPOSITORY} at commit `{SOURCE_COMMIT}`.",
        "",
        "Fonts with a Reserved Font Name are not modified: they are only converted to WOFF2 and",
        "keep their original names. The other fonts are Modified Versions: variable fonts were",
        f"instanced at weight {PINNED_WEIGHT}, and CJK and Hangul fonts were split into subsets.",
        "Their name records are unchanged.",
        "",
        "| Font | Source file | Reserved Font Name | Treatment |",
        "| --- | --- | --- | --- |",
    ]
    for item in built:
        lines.append(
            f"| {item.font.label} | `{item.upstream}` | {item.reserved_name or '—'} | {item.treatment} |"
        )
    return "\n".join([*lines, ""])


def render_outputs(built: list[Built]) -> dict[str, bytes]:
    outputs = {
        STYLESHEET: render_stylesheet(built).encode(),
        MANIFEST: render_manifest(built).encode(),
        NOTICE: render_notice(built).encode(),
    }
    for item in built:
        outputs[f"licenses/{item.font.id}.txt"] = item.license_text.encode()
    for item in built:
        for path, blob, _ in item.files:
            outputs[f"files/{path}"] = blob
    return outputs


def existing_outputs() -> set[str]:
    if not OUT_ROOT.is_dir():
        return set()
    return {str(p.relative_to(OUT_ROOT)) for p in OUT_ROOT.rglob("*") if p.is_file()}


def check_config() -> None:
    ids = [font.id for font in FONTS]
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate name font ids")
    for font in FONTS:
        if not ID_PATTERN.fullmatch(font.id):
            raise SystemExit(f"{font.id}: ids are lowercase words joined by '-'")
        if font.category not in CATEGORIES:
            raise SystemExit(f"{font.id}: unknown category {font.category!r}")


def constants_ids() -> list[str]:
    text = CONSTANTS_PATH.read_text()
    match = re.search(r"export const NAME_FONT_IDS = \[(.*?)\] as const;", text, re.S)
    if not match:
        raise SystemExit(f"{CONSTANTS_PATH.relative_to(REPO_ROOT)}: NAME_FONT_IDS not found")
    return re.findall(r"'([a-z0-9-]+)'", match.group(1))


def build(cache: Path, workers: int) -> int:
    check_config()
    lock = json.loads(LOCK_PATH.read_text()) if LOCK_PATH.is_file() else {}
    stage = cache / "name-fonts-stage"
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)
    built: list[Built] = []
    pool = ProcessPoolExecutor(max_workers=workers) if workers > 1 else None
    try:
        for font in FONTS:
            item = build_font(font, cache, stage, pool, lock)
            size = sum(len(blob) for _, blob, _ in item.files)
            print(
                f"{font.id:20} {len(item.files):3} file(s) {size / 1024:8.1f} KiB  "
                f"{','.join(item.scripts)}  [{item.treatment}]"
            )
            built.append(item)
    finally:
        if pool:
            pool.shutdown()
    shutil.rmtree(stage)

    outputs = render_outputs(built)
    for rel in sorted(existing_outputs() - set(outputs)):
        (OUT_ROOT / rel).unlink()
    for rel, blob in outputs.items():
        dest = OUT_ROOT / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        if not dest.is_file() or dest.read_bytes() != blob:
            dest.write_bytes(blob)
    for directory in sorted(OUT_ROOT.rglob("*"), reverse=True):
        if directory.is_dir() and not any(directory.iterdir()):
            directory.rmdir()

    new_lock = {
        "_comment": f"{GENERATED_HEADER} --verify checks packages/fonts/name-fonts/ against it offline.",
        "source": {"repository": SOURCE_REPOSITORY, "commit": SOURCE_COMMIT},
        "fonts": {
            item.font.id: {
                "upstream": item.upstream,
                "upstreamSha256": item.upstream_sha256,
                "license": item.license_upstream or "composed from the name table (no OFL.txt upstream)",
                "reservedFontName": item.reserved_name,
                "treatment": item.treatment,
                "files": [f"files/{path}" for path, _, _ in item.files],
            }
            for item in built
        },
        "outputs": {rel: sha256_bytes(blob) for rel, blob in sorted(outputs.items())},
    }
    LOCK_PATH.write_text(json.dumps(new_lock, indent="\t", ensure_ascii=False) + "\n")
    total = sum(len(blob) for rel, blob in outputs.items() if rel.startswith("files/"))
    print(f"wrote {OUT_ROOT.relative_to(REPO_ROOT)}/ ({total / 1024 / 1024:.1f} MiB of fonts) and {LOCK_PATH.name}")
    return verify()


FACE_RULE = re.compile(r"@font-face\s*\{(?P<body>[^}]*)\}")


def verify() -> int:
    if not LOCK_PATH.is_file():
        raise SystemExit(f"missing {LOCK_PATH}; run the build first")
    check_config()
    lock = json.loads(LOCK_PATH.read_text())
    failures: list[str] = []

    if lock["source"] != {"repository": SOURCE_REPOSITORY, "commit": SOURCE_COMMIT}:
        failures.append("the lock was built from a different source commit; rebuild")
    recorded = lock["outputs"]
    on_disk = existing_outputs()
    for extra in sorted(on_disk - set(recorded)):
        failures.append(f"name-fonts/{extra} is not recorded in {LOCK_PATH.name}")
    for rel, digest in recorded.items():
        path = OUT_ROOT / rel
        if not path.is_file():
            failures.append(f"name-fonts/{rel} is recorded in {LOCK_PATH.name} but missing")
        elif sha256_bytes(path.read_bytes()) != digest:
            failures.append(f"name-fonts/{rel}: sha256 does not match {LOCK_PATH.name}")

    config_ids = [font.id for font in FONTS]
    if list(lock["fonts"]) != config_ids:
        failures.append("the lock's fonts differ from the FONTS list; rebuild")
    manifest = json.loads((OUT_ROOT / MANIFEST).read_text()) if (OUT_ROOT / MANIFEST).is_file() else {"fonts": []}
    manifest_ids = [entry["id"] for entry in manifest["fonts"]]
    if manifest_ids != config_ids:
        failures.append("manifest.json ids differ from the FONTS list; rebuild")
    if constants_ids() != config_ids:
        failures.append(
            f"NAME_FONT_IDS in {CONSTANTS_PATH.relative_to(REPO_ROOT)} must list the same ids in the same order"
        )
    for entry in manifest["fonts"]:
        if not (OUT_ROOT / entry["license"]).is_file():
            failures.append(f"{entry['id']}: licence file {entry['license']} is missing")
        unknown = set(entry["scripts"]) - set(SCRIPT_TESTS)
        if unknown:
            failures.append(f"{entry['id']}: unknown script ids {sorted(unknown)}")

    css_path = OUT_ROOT / STYLESHEET
    faces = [m.group("body") for m in FACE_RULE.finditer(css_path.read_text())] if css_path.is_file() else []
    families = {entry["family"]: entry["id"] for entry in manifest["fonts"]}
    ranges: dict[str, set[int]] = {}
    referenced: set[str] = set()
    for body in faces:
        props = dict(
            (key.strip(), value.strip())
            for key, _, value in (line.strip().rstrip(";").partition(":") for line in body.splitlines())
            if key.strip()
        )
        family = props.get("font-family", "").strip("'")
        src = re.search(r"url\('\./(?P<path>[^']+)'\)", props.get("src", ""))
        if family not in families:
            failures.append(f"{STYLESHEET}: face for unknown family {family!r}")
            continue
        if not src:
            failures.append(f"{STYLESHEET}: {family} face without a url")
            continue
        referenced.add(src.group("path"))
        if not (OUT_ROOT / src.group("path")).is_file():
            failures.append(f"{STYLESHEET}: {src.group('path')} does not exist")
        declared = parse_unicode_range(props.get("unicode-range", ""))
        if ranges.setdefault(family, set()) & declared:
            failures.append(f"{STYLESHEET}: {family} has overlapping unicode-range faces")
        ranges[family] |= declared
        reserved = lock["fonts"][families[family]]["reservedFontName"]
        if reserved and len(lock["fonts"][families[family]]["files"]) != 1:
            failures.append(f"{family}: a reserved-name font must ship as one unmodified file")
    fonts_on_disk = {rel for rel in on_disk if rel.startswith("files/")}
    for stray in sorted(fonts_on_disk - referenced):
        failures.append(f"name-fonts/{stray} is not referenced by {STYLESHEET}")
    for family in families:
        if family not in ranges:
            failures.append(f"{STYLESHEET}: no faces for {family}")

    if failures:
        for failure in failures:
            print(f"FAIL: {failure}")
        return 1
    print(f"name fonts OK: {len(config_ids)} fonts, {len(fonts_on_disk)} files match {LOCK_PATH.name}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the display-name fonts in packages/fonts/name-fonts/.")
    parser.add_argument("--verify", action="store_true", help="offline: check the checked-in tree against the lock")
    parser.add_argument(
        "--cache-dir",
        type=Path,
        default=Path(__file__).resolve().parent / ".cache",
        help="where upstream downloads are kept (default: tools/fonts/.cache, git-ignored)",
    )
    parser.add_argument("--workers", type=int, default=min(8, os.cpu_count() or 1), help="parallel chunk builds")
    args = parser.parse_args()
    if args.verify:
        return verify()
    return build(args.cache_dir.resolve(), max(1, args.workers))


if __name__ == "__main__":
    sys.exit(main())
